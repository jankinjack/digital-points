def _response_has_error(text: str) -> bool:
    """True if any line is an OpenOCD error ('Error', 'Error: …')."""
    for line in text.splitlines():
        s = line.strip()
        if s.startswith('Error') and (len(s) == 5 or s[5] in ': '):
            return True
    return False


def _parse_mdb_response(response: str) -> bytes:
    """Parse hex bytes from ``0x08000000: 01 02 03 04``."""
    colon = response.find(':')
    if colon == -1:
        raise ValueError(f'Invalid mdb response: {response!r}')

    payload = response[colon + 1:]

    try:
        return bytes.fromhex(payload)
    except ValueError as exc:
        raw = bytes(
            int(t, 16)
            for t in payload.split()
            if len(t) == 2 and t[0] in _HEX_DIGITS and t[1] in _HEX_DIGITS
        )
        if not raw:
            raise ValueError(
                f'No hex data in mdb response: {response!r}',
            ) from exc
        return raw


